#!/bin/sh

# Generate the vkd3d-shader sources that its autotools build would generate
# into deps/extra/vkd3d/ (see deps/premake/vkd3d.lua).
#
# We build vkd3d-shader with premake, which can't run generators as autotools
# does, and Windows CI doesn't have them anyway. So we keep their output in
# the repository and rerun this script whenever the deps/vkd3d submodule
# moves to another release. The output is the same on every run with the
# same tools, so a diff shows what the new release changed.
#
# The generators are widl (MinGW-w64 and Wine both install it), bison, flex,
# and perl with the JSON module (perl-JSON on Fedora). WIDL, BISON, FLEX, and
# PERL override them.
#
usage="Usage: $0 [-h|--help]"

owd="$(pwd)"

fail ()
{
  cd "$owd" || true
  exit 1
}

diag ()
{
  echo "$*" 1>&2
}

error ()
{
  diag "error: $*"
  fail
}

run ()
{
  diag "+ $*"
  "$@"
  if test "$?" -ne 0; then
    fail
  fi
}

# Check whether the specified command exists. If the hint is provided, print
# it alongside the error.
#
check_cmd () # <cmd> [<hint>]
{
  if ! command -v "$1" >/dev/null 2>&1; then
    diag "error: unable to execute $1: command not found"
    if test -n "$2"; then
      diag "  info: $2"
    fi
    fail
  fi
}

while test $# -ne 0; do
  case "$1" in
    -h|--help)
      diag
      diag "$usage"
      diag
      exit 0
      ;;
    *)
      error "unexpected argument '$1'"
      ;;
  esac
done

src="$(cd "$(dirname "$0")/.." && pwd)"
vkd3d="$src/deps/vkd3d"
out="$src/deps/extra/vkd3d"

if test ! -f "$vkd3d/configure.ac"; then
  error "no vkd3d sources in $vkd3d"
  diag "  info: run 'git submodule update --init deps/vkd3d'"
  fail
fi

# Find widl. MinGW-w64 installs it with the target prefix and Wine
# without.
#
if test -z "$WIDL"; then
  for w in x86_64-w64-mingw32-widl widl; do
    if command -v "$w" >/dev/null 2>&1; then
      WIDL="$w"
      break
    fi
  done
fi

WIDL="${WIDL:-widl}"
BISON="${BISON:-bison}"
FLEX="${FLEX:-flex}"
PERL="${PERL:-perl}"

check_cmd "$WIDL" "install mingw-w64-tools, then rerun"
check_cmd "$BISON"
check_cmd "$FLEX"
check_cmd "$PERL"

if ! "$PERL" -MJSON -e 1 >/dev/null 2>&1; then
  error "perl JSON module is not installed"
  diag "  info: install perl-JSON, then rerun"
  fail
fi

# Take the version from configure.ac as configure would.
#
version="$(sed -n 's/^AC_INIT(\[vkd3d\],\[\([^]]*\)\].*$/\1/p' "$vkd3d/configure.ac")"

if test -z "$version"; then
  error "unable to extract version from $vkd3d/configure.ac"
fi

run mkdir -p "$out/include" "$out/libs/vkd3d-shader"
run cd "$vkd3d"

# Interface headers. Note that only other IDL files import vkd3d_unknown.idl
# (its header part is not for Windows). We skip it since MinGW-w64's widl
# fails to compile it directly (IID is undeclared outside importing files).
#
for i in include/*.idl; do
  case "$i" in
    include/vkd3d_unknown.idl) continue ;;
  esac

  run "$WIDL" -Iinclude -h -o "$out/${i%.idl}.h" "$i"
done

# SPIR-V grammar tables.
#
run "$PERL" libs/vkd3d-shader/make_spirv include/private/spirv.core.grammar.json \
  >"$out/include/spirv_grammar.h"

# HLSL and preprocessor parsers. Note that MSVC has no unistd.h, which flex
# includes unless told otherwise.
#
# Note also that we leave #line directives out: those that point to output
# files would have absolute paths.
#
for p in hlsl preproc; do
  run "$BISON" --no-lines -d -o "$out/libs/vkd3d-shader/$p.tab.c" "libs/vkd3d-shader/$p.y"
  run "$FLEX" --noline --nounistd -o "$out/libs/vkd3d-shader/$p.yy.c" "libs/vkd3d-shader/$p.l"
done

# Version, as autotools writes it for a release (without VCS id, which only
# identifies development builds).
#
echo '#define VKD3D_VCS_ID ""' >"$out/include/vkd3d_version.h"

# Configuration, which is what configure would detect on Windows with MSVC
# and MinGW-w64 alike, plus version.
#
cat >"$out/include/config.h" <<EOF
/* Generated by scripts/generate-vkd3d.sh from vkd3d $version. */

#define PACKAGE_NAME "vkd3d"
#define PACKAGE_VERSION "$version"
#define PACKAGE_STRING "vkd3d $version"

#define HAVE_SPIRV_UNIFIED1_SPIRV_H 1
#define HAVE_SPIRV_UNIFIED1_GLSL_STD_450_H 1

#if defined(_MSC_VER) || defined(__MINGW32__)
#  define HAVE__STRTOD_L 1
#  define HAVE__STRTOF_L 1
#endif
EOF

# debug.c includes unistd.h unconditionally, while MSVC doesn't have it. It
# uses nothing from it on Windows. Note that the stub goes into msvc/, which
# only the MSVC build searches, since MinGW-w64 has the real one.
#
run mkdir -p "$out/msvc"
cat >"$out/msvc/unistd.h" <<EOF
/* Generated by scripts/generate-vkd3d.sh: MSVC has no unistd.h. */
EOF

cd "$owd" || fail
diag "generated vkd3d $version sources in $out"
