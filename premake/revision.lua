-- Revision of the source tree, as recorded by git.
--
-- We number revisions with the count of commits reachable from HEAD, which
-- is also what the release tags are named after (r5318, etc).
--
local c_literal = dofile (path.join (_MAIN_SCRIPT_DIR, "premake/c-literal.lua"))

local revision = {}
revision.__index = revision

-- Note that this constructor is local to this file: a revision is only
-- created by load().
--
local function new (count, branch)
  local r = setmetatable ({}, revision)
  r.count_  = count
  r.branch_ = branch
  return r
end

-- Run git in the directory with the arguments and return its output. Fail
-- if git exits with an error.
--
local function git (directory, arguments)
  local r, code = os.outputof (
    string.format ("git -C \"%s\" %s", directory, arguments))

  if r == nil then
    premake.error ("git %s exited with code %s", arguments, tostring (code))
  end

  return r
end

-- Load the revision of the git repository in the directory.
--
function revision.load (directory)
  local count = git (directory, "rev-list --count HEAD")

  if count:match ("^%d+$") == nil then
    premake.error ("invalid commit count '%s'", count)
  end

  local branch = git (directory, "branch --show-current")

  -- On a detached HEAD, which is what CI checks out, there is no current
  -- branch. In this case we take the last ref that decorates HEAD, provided
  -- there are at least three of them, as in:
  --
  --   (HEAD, tag: r5318, origin/main, main)
  --
  -- Failing that, we assume develop.
  --
  -- @@ There is no develop branch upstream anymore, so the only builds
  --    that are experimental (see experimental()) are those that end up
  --    here.
  --
  if branch == "" then
    branch = git (directory, "show -s --pretty=%d HEAD"):match (
      ".+,.+, ([^)]+)") or "develop"
  end

  return new (count, branch)
end

-- Return the count of commits reachable from HEAD.
--
function revision:count ()
  return self.count_
end

function revision:branch ()
  return self.branch_
end

-- Return true if this is an experimental build, which is what the develop
-- branch builds.
--
function revision:experimental ()
  return self.branch_ == "develop"
end

-- Return the version string, for example, r5318-main. The branch is left
-- out for develop.
--
function revision:version ()
  local r = "r" .. self.count_

  if self.branch_ ~= "develop" then
    r = r .. "-" .. self.branch_
  end

  return r
end

-- Write the build information headers (version.h and version.hpp) into the
-- directory, creating it if necessary.
--
-- Note that we only write a header if its contents change. This way a
-- regeneration with the same revision doesn't make everything that includes
-- it out of date.
--
function revision:write (directory)
  local ok, e = os.mkdir (directory)

  if not ok then
    premake.error ("unable to create %s: %s", directory, tostring (e))
  end

  local h =
  {
    "// Build information. Generated by 'premake5 generate-buildinfo'.",
    "//",
    "#define GIT_BRANCH " .. c_literal (self.branch_),
    "#define REVISION " .. self.count_,
    "#define REVISION_STR \"r" .. self.count_ .. "\""
  }

  if self:experimental () then
    table.insert (h, "#define EXPERIMENTAL_BUILD")
  end

  local hpp =
  {
    "// Build information. Generated by 'premake5 generate-buildinfo'.",
    "//",
    "#include \"version.h\""
  }

  for _, f in ipairs ({{"version.h", h}, {"version.hpp", hpp}}) do
    local p = path.join (directory, f[1])
    local r, e = os.writefile_ifnotequal (table.concat (f[2], "\n") .. "\n", p)

    if r < 0 then
      premake.error ("unable to write %s: %s", p, tostring (e))
    end
  end
end

return revision
